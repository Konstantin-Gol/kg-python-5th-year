#string help
subject = "ComputerScience"
 
# Extract "Computer" (0 to 8)
print(subject[0:8])
 
# Extract "Science" (8 to end)
print(subject[8:])
 
# Extract first 3 characters
print(subject[:3])
 
# Extract last 3 characters
print(subject[-3:])
 
# Reverse the string
print(subject[::-1])
